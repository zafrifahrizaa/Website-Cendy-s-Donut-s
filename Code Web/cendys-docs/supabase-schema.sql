-- ============================================================================
-- SUPABASE SETUP SCRIPT FOR CENDY'S DONUT'S
-- Jalankan script ini 1 kali di Supabase Dashboard -> SQL Editor -> New Query
-- ============================================================================

-- 1. Tabel Produk
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  category text not null,
  also_in_categories text[] not null default '{}',
  subcategory text,
  price integer,
  price_variants jsonb not null default '[]'::jsonb,
  image text default '',
  description text default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

-- 2. Tabel Pengaturan Tampilan & Profil Toko
create table if not exists public.site_settings (
  id integer primary key default 1,
  brand_name text not null default 'Cendy''s Donut''s',
  hero_description text not null default 'Pabrik dan rumah produksi roti di Sidoarjo yang memproduksi aneka donat, roti lembut, bolu, hingga kue basah segar setiap hari. Melayani pembelian harian, pesanan acara keluarga, syukuran, hingga kebutuhan konsumsi partai besar.',
  hero_image text default '',
  owner_name text not null default 'Sri Wahyuni',
  business_type text not null default 'Pabrik roti / produksi roti',
  address text not null default 'Jl. Sunan Muria, RT.01/RW.01, Waras, Sugihwaras, Kec. Candi, Kabupaten Sidoarjo, Jawa Timur 61271',
  whatsapp_display text not null default '+62 857-3533-9708',
  whatsapp_number text not null default '6285735339708',
  instagram text not null default '@cendysd',
  updated_at timestamptz not null default now(),
  constraint single_row check (id = 1)
);

-- Masukkan pengaturan awal jika belum ada
insert into public.site_settings (id) values (1) on conflict (id) do nothing;

-- 3. Aktifkan Row Level Security (RLS)
alter table public.products enable row level security;
alter table public.site_settings enable row level security;

-- Kebijakan Baca: Semua pengunjung (anonim) bisa melihat produk & profil toko
create policy "Public read products"
  on public.products for select
  using (true);

create policy "Public read site_settings"
  on public.site_settings for select
  using (true);

-- Kebijakan Tulis: HANYA Admin yang sudah login (authenticated) yang bisa ubah data
create policy "Admin insert products"
  on public.products for insert
  to authenticated
  with check (true);

create policy "Admin update products"
  on public.products for update
  to authenticated
  using (true)
  with check (true);

create policy "Admin delete products"
  on public.products for delete
  to authenticated
  using (true);

create policy "Admin update site_settings"
  on public.site_settings for update
  to authenticated
  using (true)
  with check (true);

create policy "Admin insert site_settings"
  on public.site_settings for insert
  to authenticated
  with check (true);

-- 4. Storage Bucket untuk Foto Produk & Hero
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

-- Semua orang bisa melihat foto di bucket product-images
create policy "Public read product images"
  on storage.objects for select
  using (bucket_id = 'product-images');

-- Hanya Admin login yang bisa upload/ubah/hapus foto
create policy "Admin upload product images"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'product-images');

create policy "Admin update product images"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'product-images');

create policy "Admin delete product images"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'product-images');

